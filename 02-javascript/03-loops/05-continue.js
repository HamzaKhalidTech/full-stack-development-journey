// ======================================================
// 05 - CONTINUE
// ======================================================


// ======================================================
// 1. BASIC CONTINUE
// ======================================================

for (let i = 1; i <= 5; i++) {

    if (i === 3) {
        continue;
    }

    console.log(i);
}


// ======================================================
// 2. SKIP EVEN NUMBERS
// ======================================================

for (let i = 1; i <= 10; i++) {

    if (i % 2 === 0) {
        continue;
    }

    console.log(i);
}


// ======================================================
// 3. SKIP ODD NUMBERS
// ======================================================

for (let i = 1; i <= 10; i++) {

    if (i % 2 !== 0) {
        continue;
    }

    console.log(i);
}


// ======================================================
// 4. SKIP SPECIFIC NUMBER
// ======================================================

for (let i = 1; i <= 10; i++) {

    if (i === 5) {
        continue;
    }

    console.log(i);
}


// ======================================================
// 5. SKIP MULTIPLES OF 3
// ======================================================

for (let i = 1; i <= 20; i++) {

    if (i % 3 === 0) {
        continue;
    }

    console.log(i);
}


// ======================================================
// 6. ECOMMERCE EXAMPLE
// ======================================================

let prices = [1000, 2500, 0, 3500, 0, 5000];

for (let i = 0; i < prices.length; i++) {

    if (prices[i] === 0) {
        continue;
    }

    console.log(`Product Price: ${prices[i]}`);
}


// ======================================================
// 7. WHILE LOOP WITH CONTINUE
// ======================================================

let number = 1;

while (number <= 5) {

    if (number === 3) {
        number++;
        continue;
    }

    console.log(number);

    number++;
}