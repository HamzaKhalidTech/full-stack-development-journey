// ======================================================
// 01 - FOR LOOP
// ======================================================


// ======================================================
// 1. BASIC FOR LOOP
// ======================================================

for (let i = 1; i <= 5; i++) {
    console.log(i);
}


// ======================================================
// 2. PRINT 1 TO 10
// ======================================================

for (let i = 1; i <= 10; i++) {
    console.log(i);
}


// ======================================================
// 3. REVERSE LOOP
// ======================================================

for (let i = 5; i >= 1; i--) {
    console.log(i);
}


// ======================================================
// 4. EVEN NUMBERS
// ======================================================

for (let i = 1; i <= 10; i++) {
    if (i % 2 === 0) {
        console.log(i);
    }
}


// ======================================================
// 5. ODD NUMBERS
// ======================================================

for (let i = 1; i <= 10; i++) {
    if (i % 2 !== 0) {
        console.log(i);
    }
}


// ======================================================
// 6. MULTIPLICATION TABLE
// ======================================================

let number = 5;

for (let i = 1; i <= 10; i++) {
    console.log(`${number} × ${i} = ${number * i}`);
}


// ======================================================
// 7. SUM OF NUMBERS
// ======================================================

let sum = 0;

for (let i = 1; i <= 5; i++) {
    sum = sum + i;
}

console.log(`Sum: ${sum}`);


// ======================================================
// 8. ECOMMERCE EXAMPLE
// ======================================================

let total = 0;

for (let i = 1; i <= 5; i++) {
    total = total + 1000;
}

console.log(`Total Price: ${total}`);