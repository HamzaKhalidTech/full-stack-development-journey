
/*
    JavaScript Objects
    Lesson 1: Object Basics
*/

// 1. Create an object
const student = {
    name: "Hamza",
    age: 21,
    semester: 4,
    cgpa: 2.31,
    isEnrolled: true
};

// 2. Display the complete object
console.log(student);

// 3. Access individual properties
console.log(student.name);
console.log(student.age);
console.log(student.semester);
console.log(student.cgpa);
console.log(student.isEnrolled);
